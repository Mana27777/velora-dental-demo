import assert from 'node:assert/strict';
import fs from 'node:fs';
import {campaignFrom,createMeasurement} from './measurement.js';
const campaign=campaignFrom('?utm_source=revision&utm_medium=local&utm_campaign=etapa16&utm_content=card&unrelated=ignored&utm_term=not-collected');
assert.deepEqual(campaign,{utm_source:'revision',utm_medium:'local',utm_campaign:'etapa16',utm_content:'card',utm_term:'not-collected'});
assert(Object.isFrozen(campaign));
assert.equal(campaignFrom('?utm_source='+encodeURIComponent('  a\nb  ')).utm_source,'ab');
assert.equal(campaignFrom('?utm_campaign='+'x'.repeat(300)).utm_campaign.length,120);
const target=new EventTarget(),events=[];
target.addEventListener('velora:measurement',e=>events.push(e.detail));
const track=createMeasurement({target,search:'?utm_source=revision&private=ignored'});
track('education_view');track('whatsapp_cta_click');track('whatsapp_open_attempt','configured');track('appointment_confirmed');track('anything_else');
assert.equal(events.length,3);
assert.equal(events[0].section,'educacion');
assert.equal(events[1].contact_mode,'demo');
assert.equal(events[2].action,'open_attempt_only');
assert(events.every(e=>e.appointment_confirmed===false));
assert(events.every(e=>Object.keys(e.campaign).join()==='utm_source'));
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const config=fs.readFileSync(new URL('./config.js',import.meta.url),'utf8');
const faqHtml=html.slice(html.indexOf('<div class="questions">'),html.indexOf('<section class="information final-cta"'));
const summaries=[...faqHtml.matchAll(/<summary>(.*?)<\/summary>/g)].map(m=>m[1]);
assert.deepEqual(summaries,['¿Cómo sé si puedo colocarme un implante?','¿Cuánto puede costar?','¿Cuánto tiempo lleva el tratamiento?','¿Qué sucede en la primera valoración?','¿Existen alternativas a los implantes?','¿Cómo solicito un turno?','¿Voy a necesitar estudios?','¿Qué debo preguntar sobre molestias y cuidados?']);
for(const id of ['inicio','educacion','proceso','preguntas','consulta'])assert(html.includes('id="'+id+'"'));
const ids=new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
for(const link of html.matchAll(/href="#([^"]+)"/g))assert(ids.has(link[1]),'broken anchor '+link[1]);
assert.equal((html.match(/class="cta"/g)||[]).length,1);
assert.equal((html.match(/<video\b/g)||[]).length,1);
assert(!/<(?:form|input|textarea)\b/.test(html));
assert(!html.includes('<img src="/images/recepcion-velora'));
assert(html.includes('data-resource-status="schematic"'));
assert(config.includes("whatsappNumber: ''"));
assert(config.includes('Hola, quisiera solicitar una valoración de implantología. ¿Qué turnos tienen disponibles?'));
assert(!/fetch\(|localStorage|sessionStorage|sendBeacon|document\.cookie/.test(fs.readFileSync(new URL('./measurement.js',import.meta.url),'utf8')));
